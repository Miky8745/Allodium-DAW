def preset(arch: str, regions: list[str], fmt: dict | None = None, extra: str = '') -> str:
    ctl, glob = ARCH[arch]
    if fmt:
        glob = glob.format(**fmt)
    body = '\n'.join(regions)
    return f'{HEADER}\n{ctl}\n\n<global>\n{glob}\n{extra}\n{body}\n'


def region(sample: str, midi: float, extra: str = '') -> str:
    return f'<region> sample={S}{sample} {root(midi)}{(" " + extra) if extra else ""}'


def detuned(sample: str, midi: float, cents=(-9, 9), pan=50) -> list[str]:
    """Two copies a few cents apart, panned apart — a cheap chorus/width."""
    base = round((round(midi) - midi) * 100)
    return [f'<region> sample={S}{sample} pitch_keycenter={round(midi)} tune={base + c} pan={p} volume=-3'
            for c, p in zip(cents, (-pan, pan))]


def wide(sample: str, midi: float) -> list[str]:
    """Three detuned copies (supersaw-style)."""
    base = round((round(midi) - midi) * 100)
    return [f'<region> sample={S}{sample} pitch_keycenter={round(midi)} tune={base + c} pan={p} volume=-5'
            for c, p in ((-14, -60), (0, 0), (14, 60))]


