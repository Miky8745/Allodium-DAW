def root(midi: float) -> str:
    """pitch_keycenter + tune for a measured root."""
    key = round(midi)
    cents = round((key - midi) * 100)
    return f'pitch_keycenter={key}' + (f' tune={cents}' if cents else '')


# ── Macro / envelope archetypes ──────────────────────────────────────────
# Each archetype is (control block, global block). Macros are plain SFZ:
# label_ccN names a knob, set_ccN its default (0..127), <param>_onccN what
# it moves. Bloom shows the labeled CCs as its 8 macro knobs.

def control(*knobs):
    lines = ['<control>']
    for cc, label, default in knobs:
        lines.append(f'label_cc{cc}={label}')
        lines.append(f'set_cc{cc}={default}')
    return '\n'.join(lines)


